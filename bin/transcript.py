"""Shared transcript parsing and terminal text metrics.

Claude Code appends one JSON record per line to
~/.claude/projects/<cwd-slug>/<session-id>.jsonl. Only a subset of the records
with role "user" are turns a human actually typed; the rest are tool results,
subagent traffic, slash-command envelopes and injected reminders.
"""

import json
import re
import unicodedata
from datetime import datetime, timezone
from pathlib import Path

PROJECTS_ROOT = Path.home() / ".claude" / "projects"

# Envelope tags Claude Code writes into the user role that are not user turns.
NOISE_PREFIXES = (
    "<local-command-",
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<task-notification>",
    "<user-prompt-submit-hook>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<system-reminder>",
    "caveat: the messages below were generated by the user",
    "[request interrupted",
    "this session is being continued from a previous conversation",
)

COMPACTION_PREFIX = "this session is being continued from a previous conversation"

SIZE_BARS = "▁▂▃▄▅▆▇█"
SIZE_STEPS = (200, 600, 1500, 4000, 10000, 25000, 60000)

# Assistant block kinds worth showing; tool calls are deliberately not among them.
RENDERED_KINDS = ("text", "thinking")

REMINDER_RE = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
TAG_RE = re.compile(r"<(ide_[a-z_]+|ide-[a-z-]+)>.*?</\1>", re.S)
ANSI_RE = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")


# --- terminal text metrics --------------------------------------------------


def char_width(ch):
    if unicodedata.combining(ch):
        return 0
    return 2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1


def cell_width(text):
    return sum(char_width(ch) for ch in text)


def fit(text, limit):
    """Truncate to `limit` terminal cells, accounting for double-width glyphs."""
    if limit <= 0:
        return ""
    if cell_width(text) <= limit:
        return text
    out = []
    used = 0
    for ch in text:
        w = char_width(ch)
        if used + w > limit - 1:
            break
        out.append(ch)
        used += w
    return "".join(out) + "…"


def pad(text, width):
    return text + " " * max(0, width - cell_width(text))


def wrap(text, width):
    """Wrap to `width` cells, breaking on spaces when the line is space-separated."""
    if width <= 0:
        return [""]
    lines = []
    for paragraph in text.split("\n"):
        if not paragraph:
            lines.append("")
            continue
        current = ""
        used = 0
        for ch in paragraph:
            w = char_width(ch)
            if used + w > width:
                cut = current.rfind(" ")
                if cut > 0 and cell_width(current[cut + 1 :]) < width // 2:
                    lines.append(current[:cut])
                    current = current[cut + 1 :]
                    used = cell_width(current)
                else:
                    lines.append(current)
                    current = ""
                    used = 0
            current += ch
            used += w
        lines.append(current)
    return lines


# --- record classification --------------------------------------------------


def clean(text):
    text = REMINDER_RE.sub("", text)
    text = TAG_RE.sub("", text)
    return ANSI_RE.sub("", text)


def user_text(record):
    """Full text of a human-typed turn, or None for any other record."""
    if record.get("type") != "user":
        return None
    if record.get("isMeta") or record.get("isSidechain"):
        return None
    content = (record.get("message") or {}).get("content")
    if isinstance(content, str):
        text = content
    elif isinstance(content, list):
        blocks = [
            b.get("text", "")
            for b in content
            if isinstance(b, dict) and b.get("type") == "text"
        ]
        if not blocks:
            return None  # tool_result turns carry no user intent
        text = "\n".join(blocks)
    else:
        return None

    text = clean(text).strip()
    if not text:
        return None
    lowered = text.lower()
    if any(lowered.startswith(p) for p in NOISE_PREFIXES):
        return None
    return text


def raw_user_text(record):
    """User-role text before noise filtering, for classifying envelope records."""
    if record.get("type") != "user" or record.get("isSidechain"):
        return ""
    content = (record.get("message") or {}).get("content")
    if isinstance(content, str):
        text = content
    elif isinstance(content, list):
        text = "\n".join(
            b.get("text", "")
            for b in content
            if isinstance(b, dict) and b.get("type") == "text"
        )
    else:
        return ""
    return clean(text).strip()


def compaction_break(record):
    """True for the continuation notice Claude Code writes after a compaction.

    It is not a user turn, but it marks where the context was cut, which is the
    most useful landmark a long session has.
    """
    return raw_user_text(record).lower().startswith(COMPACTION_PREFIX)


def turn_text(record):
    """One-line summary of a human-typed turn, or None."""
    text = user_text(record)
    if text is None:
        return None
    for line in text.splitlines():
        line = line.strip()
        if line:
            return line
    return None


def assistant_blocks(record):
    """Blocks of an assistant record as (kind, text) pairs.

    Tool blocks are parsed but not in RENDERED_KINDS: a transcript of tool
    names carries no meaning once the reply itself is in front of you.
    """
    if record.get("type") != "assistant" or record.get("isSidechain"):
        return []
    content = (record.get("message") or {}).get("content")
    if isinstance(content, str):
        return [("text", clean(content))] if content.strip() else []
    if not isinstance(content, list):
        return []
    out = []
    for block in content:
        if not isinstance(block, dict):
            continue
        kind = block.get("type")
        if kind == "text" and block.get("text", "").strip():
            out.append(("text", clean(block["text"]).strip()))
        elif kind == "thinking" and block.get("thinking", "").strip():
            out.append(("thinking", clean(block["thinking"]).strip()))
        elif kind == "tool_use":
            out.append(("tool", block.get("name") or "tool"))
    return out


def reply_weight(record):
    """Rough size of an assistant record, in characters of rendered reply.

    Counts only what the turn view actually shows, so the size bar and the
    popup agree on how large a turn is.
    """
    return sum(len(text) for kind, text in assistant_blocks(record)
               if kind in RENDERED_KINDS)


def size_bar(weight):
    """One block glyph standing in for how large a turn's reply was."""
    level = 0
    for step in SIZE_STEPS:
        if weight < step:
            break
        level += 1
    return SIZE_BARS[level]


def local_hhmm(stamp):
    if not stamp:
        return "--:--"
    try:
        parsed = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    except ValueError:
        return "--:--"
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone().strftime("%H:%M")


# --- session files ----------------------------------------------------------


def session_path(session_id, cwd, root=None):
    root = root or PROJECTS_ROOT
    if cwd:
        direct = root / re.sub(r"[^A-Za-z0-9]", "-", cwd) / f"{session_id}.jsonl"
        if direct.exists():
            return direct
    if not root.is_dir():
        return None
    for project in root.iterdir():
        candidate = project / f"{session_id}.jsonl"
        if candidate.exists():
            return candidate
    return None


def iter_records(path):
    with path.open("rb") as handle:
        for raw in handle:
            if not raw.strip():
                continue
            try:
                yield json.loads(raw.decode("utf-8", "replace"))
            except ValueError:
                continue


def load_turn(path, ordinal):
    """Full text of the `ordinal`-th (1-based) user turn plus the reply that follows."""
    seen = 0
    turn = None
    blocks = []
    for record in iter_records(path):
        text = user_text(record)
        if text is not None:
            seen += 1
            if turn is not None:
                break  # next human turn ends this one
            if seen == ordinal:
                turn = {"text": text, "stamp": local_hhmm(record.get("timestamp"))}
            continue
        if turn is not None:
            blocks.extend(assistant_blocks(record))
    if turn is None:
        return None
    turn["blocks"] = blocks
    return turn


class SessionIndex:
    """Incrementally tails one session file; large transcripts are parsed once.

    `entries` mixes two kinds of row: a "turn" carries the ordinal `load_turn`
    expects, and a "break" marks a compaction boundary. Breaks are not counted
    as turns, so ordinals stay stable no matter how many of them appear.
    """

    def __init__(self, path):
        self.path = path
        self.offset = 0
        self.pending = b""
        self.entries = []
        self.count = 0
        self.error = None
        self._open = None  # turn whose reply is still being appended

    @property
    def turns(self):
        return [e for e in self.entries if e["kind"] == "turn"]

    def _reset(self):
        self.offset = 0
        self.pending = b""
        self.entries = []
        self.count = 0
        self._open = None

    def refresh(self):
        """Return True when the entry list or the last turn's size changed."""
        try:
            size = self.path.stat().st_size
        except OSError as exc:
            self.error = str(exc)
            return False
        self.error = None
        if size < self.offset:  # file replaced or rewritten
            self._reset()
        if size == self.offset:
            return False
        try:
            with self.path.open("rb") as handle:
                handle.seek(self.offset)
                chunk = handle.read()
        except OSError as exc:
            self.error = str(exc)
            return False
        self.offset += len(chunk)
        buf = self.pending + chunk
        cut = buf.rfind(b"\n")
        if cut < 0:
            self.pending = buf
            return False
        self.pending = buf[cut + 1 :]
        changed = False
        for raw in buf[:cut].split(b"\n"):
            if not raw.strip():
                continue
            try:
                record = json.loads(raw.decode("utf-8", "replace"))
            except ValueError:
                continue
            changed |= self._consume(record)
        return changed

    def _consume(self, record):
        summary = turn_text(record)
        if summary is not None:
            self.count += 1
            self._open = {
                "kind": "turn",
                "ordinal": self.count,
                "stamp": local_hhmm(record.get("timestamp")),
                "summary": summary,
                "weight": 0,
            }
            self.entries.append(self._open)
            return True
        if compaction_break(record):
            self._open = None
            self.entries.append({
                "kind": "break",
                "ordinal": 0,
                "stamp": local_hhmm(record.get("timestamp")),
                "summary": "",
                "weight": 0,
            })
            return True
        if self._open is not None:
            weight = reply_weight(record)
            if weight:
                self._open["weight"] += weight
                return True
        return False
